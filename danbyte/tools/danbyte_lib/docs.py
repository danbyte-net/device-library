"""``danbyte-lib docs``: the reference pages, generated from the schemas.

The schemas are the source; ``danbyte/docs/reference/*.md`` are generated and
committed, and CI runs ``danbyte-lib docs --check`` so they never drift.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from . import yamlio

HEADER = "<!-- Generated by `danbyte-lib docs` from danbyte/schema/{name}. Do not edit. -->\n"
ORDER = ["overlay.schema.json", "module-overlay.schema.json", "pluggable.schema.json",
         "rack-type.schema.json", "rack-kit.schema.json", "pack.schema.json", "meta.schema.json",
         "common.schema.json", "catalog.schema.json"]
#: Where each kind of file lives, for the editor line.
HOME = {
    "overlay.schema.json": "danbyte/overlays/<Vendor>/<model>.yaml",
    "module-overlay.schema.json": "danbyte/module-overlays/<Vendor>/<model>.yaml",
    "pluggable.schema.json": "danbyte/pluggables/<Vendor>/<NAME>.yaml",
    "rack-type.schema.json": "danbyte/racks/types/<Vendor>/<model>.yaml",
    "rack-kit.schema.json": "danbyte/racks/kits/<Vendor>/<NAME>/kit.yaml",
    "pack.schema.json": "danbyte/packs/<id>/pack.yaml",
}


def _stem(name: str) -> str:
    return name.replace(".schema.json", "")


def _anchor(text: str) -> str:
    return re.sub(r"[^a-z0-9 _-]", "", text.lower()).replace(" ", "-")


def _ref_link(ref: str, here: str) -> str:
    file, _, pointer = ref.partition("#")
    file = file or here
    name = pointer.rsplit("/", 1)[-1] if pointer else _stem(file)
    target = f"{_stem(file)}.md" if file != here else ""
    return f"[{name}]({target}#{_anchor(name)})" if pointer else f"[{name}]({_stem(file)}.md)"


def _esc(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def type_of(s, here: str) -> str:
    if s is True:
        return "any"
    if s is False:
        return "not allowed"
    if not isinstance(s, dict):
        return ""
    if "$ref" in s:
        return _ref_link(s["$ref"], here)
    if "const" in s:
        return f"`{json.dumps(s['const'])}`"
    if "enum" in s:
        return "one of " + ", ".join(f"`{v}`" for v in s["enum"])
    for key in ("allOf", "anyOf", "oneOf"):
        if key in s:
            parts = [p for p in (type_of(x, here) for x in s[key]) if p]
            if parts:
                return parts[0] if key == "allOf" else " or ".join(parts)
    t = s.get("type")
    if t == "array":
        return f"list of {type_of(s.get('items', {}), here) or 'values'}"
    if t == "object" or "properties" in s or "additionalProperties" in s:
        ap = s.get("additionalProperties")
        if isinstance(ap, dict) and not s.get("properties"):
            return f"map of name → {type_of(ap, here)}"
        return "mapping"
    if isinstance(t, list):
        return " or ".join(t)
    if t:
        extra = ""
        if "pattern" in s and t == "string":
            extra = " (pattern)"
        if "minimum" in s or "maximum" in s:
            extra = f" ({s.get('minimum', '…')}–{s.get('maximum', '…')})"
        return t + extra
    return ""


_DOCS: dict[str, dict] = {}


def _resolve(ref: str, here: str):
    file, _, pointer = ref.partition("#")
    node = _DOCS.get(file or here)
    for part in [p for p in pointer.split("/") if p]:
        if not isinstance(node, dict):
            return None
        node = node.get(part)
    return node


def _description(s, here: str = "") -> str:
    if not isinstance(s, dict):
        return ""
    if s.get("description"):
        return s["description"]
    if "$ref" in s:
        target = _resolve(s["$ref"], here)
        if isinstance(target, dict) and target.get("description"):
            return target["description"]
    for key in ("allOf", "anyOf"):
        for x in s.get(key, []):
            if isinstance(x, dict) and x.get("description"):
                return x["description"]
    return ""


def _table(schema: dict, here: str) -> list[str]:
    props = schema.get("properties") or {}
    if not props:
        return []
    req = set(schema.get("required") or [])
    lines = ["| Key | Type | Required | Description |", "|---|---|---|---|"]
    for k, v in props.items():
        lines.append(f"| `{k}` | {_esc(type_of(v, here))} | {'yes' if k in req else ''} | {_esc(_description(v, here))} |")
    ap = schema.get("additionalProperties")
    if isinstance(ap, dict):
        lines.append(f"| *other keys* | {_esc(type_of(ap, here))} | | {_esc(_description(ap, here))} |")
    return lines


def _example(schema: dict) -> list[str]:
    ex = schema.get("examples")
    if not ex:
        return []
    return ["", "Example:", "", "```yaml", yamlio.dump(ex[0]).rstrip(), "```"]


def render(name: str, doc: dict) -> str:
    here = name
    out = [HEADER.format(name=name), f"# {doc.get('title', _stem(name))}", ""]
    if doc.get("description"):
        out += [doc["description"], ""]
    out.append(f"Schema: [`danbyte/schema/{name}`](../../schema/{name}) ({doc.get('$comment', '')}).")
    if name in HOME:
        out += ["", f"Files: `{HOME[name]}`. Start each with the editor line, so VS Code (YAML extension) "
                    "completes and checks keys as you type:", "", "```yaml",
                f"# yaml-language-server: $schema=<relative path to>/danbyte/schema/{name}", "```"]
    out.append("")
    table = _table(doc, here)
    if table:
        out += ["## Keys", ""] + table
        # nested inline objects one level down
        for k, v in (doc.get("properties") or {}).items():
            if isinstance(v, dict) and v.get("properties") and "$ref" not in v:
                out += ["", f"### {k}", "", _description(v), ""] + _table(v, here) + _example(v)
    out += _example(doc)
    defs = doc.get("$defs") or {}
    if defs:
        out += ["", "## Definitions"]
        for k, v in defs.items():
            out += ["", f"### {k}", ""]
            d = _description(v)
            if d:
                out += [d, ""]
            t = _table(v, here)
            refs = [v["$ref"]] if "$ref" in v and t else []
            refs += [x["$ref"] for x in v.get("allOf", []) if isinstance(x, dict) and "$ref" in x] if t else []
            if refs:
                out += ["Also takes the keys of " + ", ".join(_ref_link(r, here) for r in refs) + ".", ""]
            if t:
                out += t
            else:
                ty = type_of(v, here)
                if ty:
                    out.append(f"Type: {ty}")
            for sub in ("properties",):
                for pk, pv in (v.get(sub) or {}).items():
                    if isinstance(pv, dict) and pv.get("properties") and "$ref" not in pv:
                        out += ["", f"#### {k}.{pk}", "", _description(pv), ""] + _table(pv, here)
            out += _example(v)
    return "\n".join(out).rstrip() + "\n"


def index(docs: dict[str, dict]) -> str:
    lines = [HEADER.format(name="*.schema.json"), "# Danbyte library reference", "",
             "One page per schema in `danbyte/schema/`, the public standard for what Danbyte adds "
             "to the NetBox device-type library (format `danbyte-library/v1`). The schemas are the "
             "source: these pages, the editor help and Danbyte's own import validation all come "
             "from them.", "", "| Page | What it describes |", "|---|---|"]
    for name in ORDER:
        if name in docs:
            d = docs[name]
            first = (d.get("description") or "").split(". ")[0].rstrip(".") + "."
            lines.append(f"| [{d.get('title', _stem(name))}]({_stem(name)}.md) | {_esc(first)} |")
    return "\n".join(lines) + "\n"


def generate(schema_dir: Path) -> dict[str, str]:
    """``{file name: markdown}`` for every schema plus README.md."""
    docs = {}
    for f in sorted(schema_dir.glob("*.schema.json")):
        docs[f.name] = json.loads(f.read_text(encoding="utf-8"))
    _DOCS.clear()
    _DOCS.update(docs)
    pages = {f"{_stem(n)}.md": render(n, d) for n, d in docs.items()}
    pages["README.md"] = index(docs)
    return pages


def write(schema_dir: Path, out: Path, check: bool = False) -> list[str]:
    """Write the pages (or, with ``check``, list the ones that are out of date)."""
    pages = generate(schema_dir)
    stale = []
    for fname, text in pages.items():
        p = out / fname
        if check:
            if not p.is_file() or p.read_text(encoding="utf-8") != text:
                stale.append(fname)
            continue
        out.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    if check:
        known = set(pages)
        stale += [p.name + " (no schema)" for p in out.glob("*.md") if p.name not in known] if out.is_dir() else []
    return stale
